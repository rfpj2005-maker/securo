// Release signing: loads android/keystore.properties if present (created by
// the setup script, never committed — see android/.gitignore). Falls back to
// debug signing when it's missing so a fresh checkout still builds; the
// release APK we actually hand out is always built with the real keystore.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties()
val hasReleaseKeystore = keystorePropertiesFile.exists()
if (hasReleaseKeystore) {
    keystoreProperties.load(keystorePropertiesFile.inputStream())
}

